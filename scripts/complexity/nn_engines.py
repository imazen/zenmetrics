"""NN metrics across engines (rten CPU, ort-cuda, ort-webgpu): figure and table.

Reads benchmarks/iqa_complexity_2026-10-17/measured/i265_nn_1024.tsv (rten, 8-thread rows) and
benchmarks/iqa_complexity_2026-10-17/engines/i265_nn_ort-{cuda,webgpu}_1024.tsv; writes
docs/paper/fig/nn_engines.svg and docs/paper/NN_ENGINES.md. Run from the repository root.
"""
import csv, math, statistics
from pathlib import Path

B = Path('benchmarks/iqa_complexity_2026-10-17')
ENGINES = [('rten (CPU, 8 threads)', B/'measured/i265_nn_1024.tsv', '#4c72b0', 'circle'),
           ('ORT CUDA (RTX 4080)', B/'engines/i265_nn_ort-cuda_1024.tsv', '#c44e52', 'square'),
           ('ORT WebGPU (RTX 4080)', B/'engines/i265_nn_ort-webgpu_1024.tsv', '#8172b2', 'triangle')]
CPU_BOUND = 2.0  # host CPU time above this multiple of wall time: part of the work runs on the CPU


def load(path):
    rows = {}
    for r in csv.DictReader((l for l in path.read_text().splitlines() if not l.startswith('#')), delimiter='\t'):
        if r['shape'] != '1024x1024' or r['threads'] != '8' or r['wall_ms_per_call'] in ('', 'error'):
            continue
        rows.setdefault(r['metric'], []).append((float(r['wall_ms_per_call']), float(r['task_clock_ms_per_call'])))
    return {m: (statistics.median(w for w, _ in v), statistics.median(c for _, c in v)) for m, v in rows.items()}


data = [load(p) for _, p, _, _ in ENGINES]
models = sorted(set(data[1]) | set(data[2]), key=lambda m: -data[0].get(m, (0, 0))[0])

W, top, row_h, left, right = 760, 50, 18, 130, 40
H = top + row_h * len(models) + 80
lo, hi = 1.0, 2e5
x = lambda ms: left + (math.log10(ms) - math.log10(lo)) / (math.log10(hi) - math.log10(lo)) * (W - left - right)
out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="sans-serif" font-size="11">',
       f'<rect width="{W}" height="{H}" fill="white"/>',
       f'<text x="{W/2}" y="20" text-anchor="middle" font-size="13">Wall time per call by engine (i265, 1024², same models and input)</text>']
for d in range(0, 6):
    v = 10 ** d
    out.append(f'<path d="M{x(v):.1f} {top-6}V{H-55}" stroke="#ddd"/><text x="{x(v):.1f}" y="{H-42}" text-anchor="middle">{v:g} ms</text>')
for i, m in enumerate(models):
    y = top + i * row_h + row_h / 2
    out.append(f'<text x="{left-8}" y="{y+4:.1f}" text-anchor="end">{m}</text>')
    pts = [d[m][0] for d in data if m in d]
    if pts:
        out.append(f'<path d="M{x(min(pts)):.1f} {y:.1f}H{x(max(pts)):.1f}" stroke="#bbb"/>')
    for (name, _, col, shape), d in zip(ENGINES, data):
        if m not in d:
            continue
        wall, cpu = d[m]
        fill = 'white' if (shape != 'circle' and cpu > CPU_BOUND * wall) else col
        cx = x(wall)
        if shape == 'circle':
            out.append(f'<circle cx="{cx:.1f}" cy="{y:.1f}" r="4" fill="{fill}" stroke="{col}" stroke-width="1.5"><title>{m} {name}: {wall:.1f} ms</title></circle>')
        elif shape == 'square':
            out.append(f'<rect x="{cx-4:.1f}" y="{y-4:.1f}" width="8" height="8" fill="{fill}" stroke="{col}" stroke-width="1.5"><title>{m} {name}: {wall:.1f} ms (CPU {cpu:.0f} ms)</title></rect>')
        else:
            out.append(f'<path d="M{cx:.1f} {y-5:.1f}L{cx+5:.1f} {y+4:.1f}H{cx-5:.1f}Z" fill="{fill}" stroke="{col}" stroke-width="1.5"><title>{m} {name}: {wall:.1f} ms (CPU {cpu:.0f} ms)</title></path>')
ly = H - 22
for k, (name, _, col, shape) in enumerate(ENGINES):
    lx = left + k * 200
    out.append({'circle': f'<circle cx="{lx}" cy="{ly-4}" r="4" fill="{col}"/>',
                'square': f'<rect x="{lx-4}" y="{ly-8}" width="8" height="8" fill="{col}"/>',
                'triangle': f'<path d="M{lx} {ly-9}L{lx+5} {ly}H{lx-5}Z" fill="{col}"/>'}[shape])
    out.append(f'<text x="{lx+10}" y="{ly}">{name}</text>')
out.append(f'<text x="{left-10}" y="{ly+16}">hollow: GPU run whose host CPU time exceeds {CPU_BOUND:g}× its wall time</text>')
out.append('</svg>')
Path('docs/paper/fig/nn_engines.svg').write_text('\n'.join(out) + '\n')

md = ['# NN metrics across engines', '',
      'Generated by `scripts/complexity/nn_engines.py` from the timing tables in',
      '`benchmarks/iqa_complexity_2026-10-17/` (method, binary and caveats: `engines/README.md`).',
      'Same models, same 1024×1024 input pair, same 8-thread budget on i265; only the engine differs.',
      f'"CPU-bound part" marks a GPU engine whose host CPU time exceeds {CPU_BOUND:g}× its wall time.', '',
      'DMM and PieAPP spend about as much host CPU time as wall time on both GPU engines (4.1 s and',
      '3.9 s on CUDA), so their GPU runs are also limited by host-side work; which step is not',
      'measured here. CUDA/WebGPU wall includes host-to-device upload of the input pair.', '',
      '![wall time per call by engine](fig/nn_engines.svg)', '',
      '| model | rten wall ms | CUDA wall ms | CUDA host CPU ms | WebGPU wall ms | WebGPU host CPU ms | rten / CUDA |',
      '|---|---:|---:|---:|---:|---:|---:|']
for m in models:
    r, c, g = (d.get(m) for d in data)
    f = lambda v, i: f'{v[i]:.1f}' if v else '—'
    flag = lambda v: ' (CPU-bound part)' if v and v[1] > CPU_BOUND * v[0] else ''
    ratio = f'{r[0]/c[0]:.0f}×' if r and c else '—'
    md.append(f'| {m} | {f(r,0)} | {f(c,0)}{flag(c)} | {f(c,1)} | {f(g,0) if g else "unsupported ops"}{flag(g)} | {f(g,1)} | {ratio} |')
Path('docs/paper/NN_ENGINES.md').write_text('\n'.join(md) + '\n')
print(len(models), 'models')
