#!/usr/bin/env python3
"""Independent Student fixtures; run from this crate with scipy installed.

python3 scripts/student_reference.py > tests/data/student_reference.rs
"""
import scipy
from scipy.stats import t

print('// Generated by scripts/student_reference.py; scipy ' + scipy.__version__)
print('// Synthetic distribution values only. Columns: df, p, ppf(p), sf(ppf(p)).')
print('pub(crate) const QUANTILES: &[(f64, f64, f64, f64)] = &[')
for df in (1., 2., 9., 30.):
    for k in range(1, 10):
        alpha = .05 / k
        for p in (alpha, 1 - alpha):
            x = float(t.ppf(p, df))
            print(f'    ({df!r}, {p!r}, {x!r}, {float(t.sf(x, df))!r}),')
print('];')
print('pub(crate) const TAILS: &[(f64, f64, f64)] = &[')
for df in (1., 2., 9., 30.):
    for x in (-100., -10., -5., 0., 5., 10., 100.):
        print(f'    ({df!r}, {x!r}, {float(t.sf(x, df))!r}),')
print('];')
