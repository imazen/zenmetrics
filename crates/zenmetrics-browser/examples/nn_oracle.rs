//! Native scores of the learned metrics the browser runs, on the rten
//! (CPU) engine, for the Pages check's fixed pairs. Reads the exported
//! models from `ZENMETRICS_NN_MODEL_DIR`, as the CLI does (WaDIQaM's from
//! `ZENMETRICS_NN_WADIQAM_DIR` and WD's from `ZENMETRICS_NN_WD_DIR`, their own
//! export sets), and prints JSON.
use zenmetrics_abstractions::zenpixels::{PixelDescriptor, PixelSlice};
use zenmetrics_abstractions::{EvalOpts, Image, Metric, PairedNoReference};
use zenmetrics_nn::{
    Arniqa, Ckdn, DeepDc, Dists, Engine, Hyperiqa, Lpips, LpipsNet, Maniqa, Musiq, WadiqamFr,
    WadiqamKind, WadiqamNr, WassersteinDistortion, WeightsConsent,
};

/// The fixed pairs, as packed RGB8: the 256×256 scalar fixture and the
/// 480×352 map fixture of `check-pages.py`, generated by the same formulas.
fn pairs() -> Vec<(&'static str, usize, usize, Vec<u8>, Vec<u8>)> {
    let fixture = |side: usize| {
        let (mut r, mut d) = (Vec::new(), Vec::new());
        for i in 0..side * side * 4 {
            if i % 4 == 3 {
                continue;
            }
            let v = ((i * 13 + i / (side * 4) * 17) % 256) as u8;
            r.push(v);
            d.push(v.saturating_sub(7));
        }
        (r, d)
    };
    let (r256, d256) = fixture(256);
    let (w, h) = (480usize, 352usize);
    let (mut r, mut d) = (Vec::new(), Vec::new());
    for y in 0..h {
        for x in 0..w {
            for c in 0..3 {
                let v = (x * 7 + y * 5 + c * 61 + (x * y) % 23) % 256;
                r.push(v as u8);
                d.push(if (y / 24) % 3 == 0 {
                    (v / 4 * 3 + 32) as u8
                } else if c == 2 && (x / 32) % 3 == 0 {
                    (v >> 1) as u8
                } else {
                    v as u8
                });
            }
        }
    }
    vec![
        ("fixture256", 256, 256, r256, d256),
        ("unified480x352", w, h, r, d),
    ]
}

fn main() {
    let dir = std::env::var("ZENMETRICS_NN_MODEL_DIR").expect("ZENMETRICS_NN_MODEL_DIR");
    let wadiqam = std::env::var("ZENMETRICS_NN_WADIQAM_DIR").expect("ZENMETRICS_NN_WADIQAM_DIR");
    let wd = std::env::var("ZENMETRICS_NN_WD_DIR").expect("ZENMETRICS_NN_WD_DIR");
    let mut consent = WeightsConsent::new();
    for model in std::env::var("ZENMETRICS_NN_ACCEPT_WEIGHTS")
        .unwrap_or_default()
        .split(',')
    {
        consent = match model {
            "ckdn" => consent.accept(Ckdn::WEIGHTS),
            "hyperiqa" => consent.accept(Hyperiqa::WEIGHTS),
            _ => consent,
        };
    }
    let engine = Engine::Rten;
    let lpips = |net| -> Box<dyn Metric> { Box::new(Lpips::from_dir(&dir, net, engine).unwrap()) };
    let only: Vec<String> = std::env::args().skip(1).collect();
    let models: Vec<(&str, Box<dyn Fn() -> Box<dyn Metric>>)> = vec![
        (
            "ckdn",
            Box::new(|| Box::new(Ckdn::from_dir(&dir, engine, &consent).unwrap())),
        ),
        (
            "hyperiqa",
            Box::new(|| {
                Box::new(PairedNoReference::new(
                    Hyperiqa::from_dir(&dir, engine, &consent).unwrap(),
                ))
            }),
        ),
        ("lpips-alex", Box::new(|| lpips(LpipsNet::Alex))),
        ("lpips-vgg", Box::new(|| lpips(LpipsNet::Vgg))),
        ("lpips-squeeze", Box::new(|| lpips(LpipsNet::Squeeze))),
        (
            "stlpips-alex",
            Box::new(|| lpips(LpipsNet::AlexShiftTolerant)),
        ),
        (
            "stlpips-vgg",
            Box::new(|| lpips(LpipsNet::VggShiftTolerant)),
        ),
        (
            "dists",
            Box::new(|| Box::new(Dists::from_dir(&dir, engine).unwrap())),
        ),
        (
            "deepdc",
            Box::new(|| Box::new(DeepDc::from_dir(&dir, engine).unwrap())),
        ),
        (
            "arniqa",
            Box::new(|| {
                Box::new(PairedNoReference::new(
                    Arniqa::from_dir(&dir, engine).unwrap(),
                ))
            }),
        ),
        (
            "maniqa",
            Box::new(|| {
                Box::new(PairedNoReference::new(
                    Maniqa::from_dir(&dir, engine).unwrap(),
                ))
            }),
        ),
        (
            "musiq",
            Box::new(|| {
                Box::new(PairedNoReference::new(
                    Musiq::from_dir(&dir, engine).unwrap(),
                ))
            }),
        ),
        (
            "wadiqam-fr-live",
            Box::new(|| {
                Box::new(WadiqamFr::from_dir(&wadiqam, engine, WadiqamKind::FrLive).unwrap())
            }),
        ),
        (
            "wadiqam-fr-tid",
            Box::new(|| {
                Box::new(WadiqamFr::from_dir(&wadiqam, engine, WadiqamKind::FrTid).unwrap())
            }),
        ),
        (
            "wadiqam-nr-live",
            Box::new(|| {
                Box::new(PairedNoReference::new(
                    WadiqamNr::from_dir(&wadiqam, engine, WadiqamKind::NrLive).unwrap(),
                ))
            }),
        ),
        (
            "wadiqam-nr-tid",
            Box::new(|| {
                Box::new(PairedNoReference::new(
                    WadiqamNr::from_dir(&wadiqam, engine, WadiqamKind::NrTid).unwrap(),
                ))
            }),
        ),
        (
            "wd",
            Box::new(|| Box::new(WassersteinDistortion::from_dir(&wd, engine).unwrap())),
        ),
    ];
    let pairs = pairs();
    let mut out = serde_json::Map::new();
    for (name, make) in &models {
        if (only.is_empty() && matches!(*name, "ckdn" | "hyperiqa"))
            || (!only.is_empty() && !only.iter().any(|o| o == name))
        {
            continue;
        }
        let mut metric = make();
        let mut per_pair = serde_json::Map::new();
        for (pair, w, h, r, d) in &pairs {
            fn image(px: &[u8], w: usize, h: usize) -> Image<'_> {
                Image::from(
                    PixelSlice::new(px, w as u32, h as u32, w * 3, PixelDescriptor::RGB8_SRGB)
                        .unwrap(),
                )
            }
            let started = std::time::Instant::now();
            let eval = metric
                .evaluate(image(r, *w, *h), image(d, *w, *h), EvalOpts::new())
                .unwrap();
            let scores: serde_json::Map<_, _> = eval
                .scores()
                .map(|(k, v)| (k.into_owned(), serde_json::json!(v)))
                .collect();
            per_pair.insert(
                (*pair).into(),
                serde_json::json!({"scores": scores, "seconds": started.elapsed().as_secs_f64()}),
            );
        }
        out.insert((*name).into(), serde_json::Value::Object(per_pair));
        eprintln!("{name} done");
    }
    println!("{}", serde_json::json!({"engine":"rten","scores":out}));
}
