#!/usr/bin/env python3
"""Regenerate aligned little-endian fixed model data and params.rs.

Run with the pinned piq 0.8.0 / torch 2.14.1 oracle environment:
    ~/tmp/nr-classic-scratch/venv/bin/python crates/brisque/tests/gen_params.py

Outputs src/params.bin, src/params.sha256 and the small safe Rust decoder.
LIVE allmodel components are verified against the piq model after f32 rounding.
The gamma grids are retained because the measured f64 libm replacement exceeds
JND/1000; see benchmarks/brisque_review_2026-10-15/README.md.
"""
import hashlib
import io
import sys
import re
import struct
import subprocess
from pathlib import Path

import numpy as np
import torch
import piq.functional

torch.set_num_threads(1)

SCRATCH = Path.home() / "tmp" / "nr-classic-scratch"
PT = SCRATCH / "brisque_svm_weights.pt"
LIVE = SCRATCH / "brisque_release" / "BRISQUE_release"
ZIP = SCRATCH / "brisque_release" / "BRISQUE_release.zip"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def fmt_f32(v: float) -> str:
    """Exact round-trip f32 literal (shortest)."""
    return f"{np.float32(v)!s}f32"


def main() -> None:
    sv_coef, sv = torch.load(io.BytesIO(PT.read_bytes()), map_location="cpu",
                             weights_only=False)
    assert sv_coef.shape == (774,) and sv.shape == (774, 36)
    assert sv_coef.dtype == torch.float32 and sv.dtype == torch.float32

    # Verify the released plain-text model, including every coefficient and SV.
    lines = (LIVE / "allmodel").read_text().split("\nSV\n", 1)[1].splitlines()
    live_coef, live_sv = [], []
    for line in lines:
        fields = line.split()
        live_coef.append(float(fields[0]))
        row = [0.0] * 36
        for field in fields[1:]:
            index, value = field.split(":")
            row[int(index) - 1] = float(value)
        live_sv.append(row)
    assert np.array_equal(np.asarray(live_coef, dtype="<f4").view("<u4"), sv_coef.numpy().view("<u4"))
    assert np.array_equal(np.asarray(live_sv, dtype="<f4").view("<u4"), sv.numpy().view("<u4"))

    coef = sv_coef.tolist()
    vecs = sv.tolist()
    rho = -153.591

    out = io.StringIO()
    out.write("""// Generated by crates/brisque/tests/gen_params.py — do not edit.
#![allow(clippy::large_const_arrays)]
//
// BRISQUE SVR model: 774 support vectors x 36 features + coefficients,
// from piq 0.8.0's `brisque_svm_weights.pt`, bitwise identical to LIVE's
// released `allmodel` (epsilon-SVR, RBF gamma=0.05, rho=-153.591).
// The `allrange` scaling bounds live in `lib.rs` (`FEATURE_RANGES`).
//
// Provenance sha256:
""")
    out.write(f"//   brisque_svm_weights.pt: {sha(PT)}\n")
    out.write(f"//   LIVE allmodel:          {sha(LIVE / 'allmodel')}\n")
    out.write(f"//   LIVE allrange:          {sha(LIVE / 'allrange')}\n")
    out.write(f"//   BRISQUE_release.zip:    {sha(ZIP)}\n")
    out.write("\n/// SVR intercept (rho), negated as in piq: score = kernel@coef - rho.\n")
    out.write(f"pub(crate) const RHO: f32 = {fmt_f32(rho)};\n\n")
    out.write("/// Support-vector coefficients (libsvm alpha*y).\n")
    out.write("pub(crate) const SV_COEF: [f32; 774] = [\n")
    for i in range(0, 774, 6):
        out.write("    " + ", ".join(fmt_f32(v) for v in coef[i:i + 6]) + ",\n")
    out.write("];\n\n")
    out.write("/// Support vectors, row-major [774][36].\n")
    out.write("pub(crate) const SV: [[f32; 36]; 774] = [\n")
    for row in vecs:
        out.write("    [" + ", ".join(fmt_f32(v) for v in row) + "],\n")
    out.write("];\n\n")

    # Fixed gam-grid tables, computed with the oracle's own torch calls
    # (vectorized elementwise path — the same kernels piq hits on CPU).
    gamma = torch.arange(0.2, 10 + 0.001, 0.001, dtype=torch.float32)
    assert gamma.shape == (9801,)
    r_ggd = (torch.lgamma(1. / gamma) + torch.lgamma(3. / gamma)
             - 2 * torch.lgamma(2. / gamma)).exp()
    r_aggd = torch.exp(2 * torch.lgamma(2. / gamma)
                       - torch.lgamma(1. / gamma) - torch.lgamma(3. / gamma))
    out.write("/// `r_table` of piq's `_ggd_parameters` "
              "(exp(lg(1/g)+lg(3/g)-2lg(2/g))), oracle-computed.\n")
    out.write("pub(crate) const R_GGD: [f32; 9801] = [\n")
    rg = r_ggd.tolist()
    for i in range(0, 9801, 6):
        out.write("    " + ", ".join(fmt_f32(v) for v in rg[i:i + 6]) + ",\n")
    out.write("];\n\n")
    out.write("/// `r_table` of piq's `_aggd_parameters` "
              "(exp(2lg(2/g)-lg(1/g)-lg(3/g))), oracle-computed.\n")
    out.write("pub(crate) const R_AGGD: [f32; 9801] = [\n")
    ra = r_aggd.tolist()
    for i in range(0, 9801, 6):
        out.write("    " + ", ".join(fmt_f32(v) for v in ra[i:i + 6]) + ",\n")
    out.write("];\n\n")

    # ETA_FACTOR[i] = exp(lg(2/a) - (lg(1/a)+lg(3/a))/2) for a = gamma[i],
    # computed on [1]-element tensors so every op takes the scalar tail
    # path — exactly the dispatch piq sees for the per-image `eta`.
    out.write("/// `exp(lg(2/a) - (lg(1/a)+lg(3/a))/2)` per gam index "
              "(scalar-tail kernels, oracle-computed).\n")
    out.write("pub(crate) const ETA_FACTOR: [f32; 9801] = [\n")
    ef = []
    for i in range(9801):
        a = gamma[i:i + 1]
        v = torch.exp(torch.lgamma(2. / a)
                      - (torch.lgamma(1. / a) + torch.lgamma(3. / a)) / 2)
        ef.append(v.item())
        if i % 2000 == 1999:
            print(f"eta_factor {i + 1}/9801", file=sys.stderr)
    for i in range(0, 9801, 6):
        out.write("    " + ", ".join(fmt_f32(v) for v in ef[i:i + 6]) + ",\n")
    out.write("];\n\n")

    # piq's gaussian_filter(7, 7/6) — post-normalization bits.
    k = piq.functional.gaussian_filter(kernel_size=7, sigma=7. / 6,
                                       dtype=torch.float32)
    assert k.shape == (1, 7, 7)
    out.write("/// piq `gaussian_filter(7, 7/6)` (normalized), row-major.\n")
    out.write("pub(crate) const KERNEL49: [f32; 49] = [\n")
    kf = k.reshape(-1).tolist()
    for i in range(0, 49, 7):
        out.write("    " + ", ".join(fmt_f32(v) for v in kf[i:i + 7]) + ",\n")
    out.write("];\n")

    text = out.getvalue()
    names = [("RHO", 1), ("SV_COEF", 774), ("SV", 774 * 36),
             ("R_GGD", 9801), ("R_AGGD", 9801), ("ETA_FACTOR", 9801), ("KERNEL49", 49)]
    data = bytearray()
    offsets = {}
    for name, count in names:
        value = text.split(f"pub(crate) const {name}:", 1)[1].split("=", 1)[1].split(";", 1)[0]
        values = [float(x) for x in re.findall(r"([-+0-9.eE]+)f32", value)]
        assert len(values) == count, (name, len(values))
        offsets[name] = len(data)
        data.extend(struct.pack(f"<{count}f", *values))
    dest = Path(__file__).resolve().parents[1] / "src"
    (dest / "params.bin").write_bytes(data)
    digest = hashlib.sha256(data).hexdigest()
    (dest / "params.sha256").write_text(f"{digest}  params.bin\n")
    header = text.split("/// SVR intercept", 1)[0]
    decoder = header + f"// params.bin sha256: {digest}\n"
    decoder += f"""
#[repr(C, align(8))]
struct Aligned([u8; {len(data)}]);
static DATA: Aligned = Aligned(*include_bytes!("params.bin"));

const fn read<const N: usize>(offset: usize) -> [f32; N] {{
    let mut values = [0.0; N];
    let mut i = 0;
    while i < N {{
        let p = offset + i * 4;
        values[i] = f32::from_le_bytes([DATA.0[p], DATA.0[p+1], DATA.0[p+2], DATA.0[p+3]]);
        i += 1;
    }}
    values
}}
const fn support_vectors() -> [[f32; 36]; 774] {{
    let mut rows = [[0.0; 36]; 774];
    let mut i = 0;
    while i < 774 {{
        rows[i] = read::<36>({offsets['SV']} + i * 36 * 4);
        i += 1;
    }}
    rows
}}
pub(crate) const RHO: f32 = read::<1>({offsets['RHO']})[0];
pub(crate) static SV: [[f32; 36]; 774] = support_vectors();
"""
    for name, count in names:
        if name not in ("RHO", "SV"):
            decoder += f"pub(crate) static {name}: [f32; {count}] = read::<{count}>({offsets[name]});\n"
    (dest / "params.rs").write_text(decoder)
    subprocess.run(["rustfmt", "--edition", "2024", str(dest / "params.rs")], check=True)
    print(f"params.bin: {len(data)} bytes, sha256 {digest}")


if __name__ == "__main__":
    main()
