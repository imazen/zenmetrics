#!/usr/bin/env python3
"""Regenerate `crates/niqe/src/params.rs` from BasicSR's npz.

    ~/tmp/nr-classic-scratch/venv/bin/python crates/niqe/tests/gen_params.py \
        > crates/niqe/src/params.rs

Input provenance (sha256, verified 2026-10-15):
    niqe_pris_params.npz  2a7c182a68c9e7f1b2e2e5ec723279d6f65d912b6fcaf37eb2bf03d7367c4296
    niqe_release.zip      3d613b077a1b08273c79999f2e1643d5b2d9b2d0d3f3aa622236fc9592ea857c
    modelparameters.mat   fa2aa4d12dd9595c3fb6bf8b4e1a15c79d5d1469238d0901c88dead195be578d
        (inside niqe_release.zip under niqe_release/; its `mu`/`cov`/`win`
        arrays are bit-identical to the npz, maxdiff 0.0)

The npz is BasicSR 1.4.2's `basicsr/metrics/niqe_pris_params.npz`
(Apache-2.0); the underlying data is LIVE's niqe_release pristine MVG,
whose notice (`LICENSE-LIVE-niqe`) must accompany copies.
"""
import sys
from pathlib import Path

import numpy as np

NPZ = Path(sys.argv[1]) if len(sys.argv) > 1 else (
    Path.home() / "tmp/nr-classic-scratch/niqe_pris_params.npz"
)

HEADER = """\
//! LIVE NIQE pristine-model parameters (36-dim MVG on AGGD features).
//! Generated from BasicSR's `basicsr/metrics/niqe_pris_params.npz`
//! (sha256 2a7c182a68c9e7f1b2e2e5ec723279d6f65d912b6fcaf37eb2bf03d7367c4296),
//! which is bit-identical to `modelparameters.mat` (sha256
//! fa2aa4d12dd9595c3fb6bf8b4e1a15c79d5d1469238d0901c88dead195be578d) in
//! LIVE's `niqe_release.zip` (sha256
//! 3d613b077a1b08273c79999f2e1643d5b2d9b2d0d3f3aa622236fc9592ea857c;
//! verified 2026-10-15, maxdiff 0.0). Licence: `LICENSE-LIVE-niqe` (the
//! LIVE copyright notice) must accompany copies.
//! Regenerated by `tests/gen_params.py` — do not edit by hand.
"""


def emit(name: str, a: np.ndarray) -> str:
    flat = np.ascontiguousarray(a, dtype=np.float64).ravel()
    n = "36 * 36" if name == "COV_PRIS" else str(flat.size)
    lines = [f"pub(crate) static {name}: [f64; {n}] = ["]
    for v in flat:
        bits = np.float64(v).view(np.uint64)
        lines.append(f"    f64::from_bits(0x{bits:016x}),")
    lines.append("];\n")
    return "\n".join(lines)


def main() -> None:
    z = np.load(NPZ)
    sys.stdout.write(HEADER)
    sys.stdout.write(emit("MU_PRIS", z["mu_pris_param"]))
    sys.stdout.write(emit("COV_PRIS", z["cov_pris_param"]))
    sys.stdout.write(emit("GAUSS_WINDOW", z["gaussian_window"]))


if __name__ == "__main__":
    main()
