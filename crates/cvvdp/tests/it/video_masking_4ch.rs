#[test]
fn mult_mutual_4ch_matches_pycvvdp_0_5_7() {
    let n = 64usize;
    let mut t_p: [Vec<f32>; 4] = [vec![0.0; n], vec![0.0; n], vec![0.0; n], vec![0.0; n]];
    let mut r_p: [Vec<f32>; 4] = [vec![0.0; n], vec![0.0; n], vec![0.0; n], vec![0.0; n]];
    for c in 0..4 {
        for i in 0..n {
            t_p[c][i] = T_IN[c][i] * S_IN[c][i] * CH_GAIN_4[c];
            r_p[c][i] = R_IN[c][i] * S_IN[c][i] * CH_GAIN_4[c];
        }
    }
    let d = mult_mutual_band_4ch(&t_p, &r_p, 8, 8);
    let mut max_abs = 0.0f32;
    for c in 0..4 {
        for i in 0..n {
            let diff = (d[c][i] - D_EXP[c][i]).abs();
            max_abs = max_abs.max(diff);
            // Values range to ~18; tolerate 1e-3 abs / 1e-4 rel.
            let tol = 1e-3f32.max(D_EXP[c][i].abs() * 1e-4);
            assert!(diff < tol, "ch={c} px={i}: {} vs {}", d[c][i], D_EXP[c][i]);
        }
    }
    eprintln!("mult_mutual_4ch max |Δ| vs pycvvdp: {max_abs:.3e}");
}
