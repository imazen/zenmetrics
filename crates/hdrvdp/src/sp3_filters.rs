//! `.m` source rather than typed by hand.
//!
//! Transform: E. P. Simoncelli & W. T. Freeman, *"The Steerable Pyramid: A
//! Flexible Architecture for Multi-Scale Derivative Computation"*, ICIP 1995.
//! Kernel design: A. Karasaridis & E. P. Simoncelli, *"A Filter Design
//! Technique for Steerable Pyramid Image Transforms"*, ICASSP 1996.
//!
//! ## The one transcription trap
//!
//! `bfilts` is stored in the `.m` file as a 4×81 literal that is immediately
//! **transposed** (`]'`), and each column is then read back with MATLAB's
//! **column-major** `reshape(bfilts(:,b), 9, 9)`. The net effect is that the
//! 9 lines written per band in the source are the filter's *columns*, not its
//! rows — i.e. `filt[i][j] = written_flat[j*9 + i]`. Reading them as rows
//! silently transposes every oriented filter, which swaps the horizontal and
//! vertical bands and mirrors the two diagonals. The tables below are already
//! un-transposed into row-major filter order.

